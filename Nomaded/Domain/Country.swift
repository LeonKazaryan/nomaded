/// A place on the globe that can be marked: a country or a territory. Static data from
/// `Resources/Geo/countries.json`, generated by Tools/GeoPipeline. Names and flags come
/// from the code (`RegionDisplay`).
struct Country: Codable, Sendable, Identifiable {
    let code: String
    let continent: Continent
    let subregion: Subregion
    /// One of the 195 countries "% of the world" counts. Otherwise a territory, like
    /// Greenland or Puerto Rico.
    let isSovereign: Bool
    /// From Natural Earth's outlines: good for big places, rough for microstates (the
    /// Vatican comes out far too small), so don't show it as a number.
    let areaKm2: Double

    var id: String { code }

    private enum CodingKeys: String, CodingKey {
        case code, continent, subregion, areaKm2
        case isSovereign = "sovereign"
    }
}

struct CountryCatalog: Sendable {
    let countries: [Country]
    private let byCode: [String: Country]

    init(_ countries: [Country]) {
        self.countries = countries
        byCode = Dictionary(countries.map { ($0.code, $0) }, uniquingKeysWith: { first, _ in first })
    }

    subscript(code: String) -> Country? { byCode[code] }

    /// The bundled catalog. A few dozen kilobytes, so it loads on first use.
    static let bundled: CountryCatalog = {
        do {
            return try loadBundled()
        } catch {
            assertionFailure("countries.json failed to load: \(error)")
            return CountryCatalog([])
        }
    }()

    static func loadBundled() throws -> CountryCatalog {
        guard let url = Bundle.main.url(forResource: "countries", withExtension: "json") else {
            throw CocoaError(.fileNoSuchFile)
        }
        return CountryCatalog(try JSONDecoder().decode([Country].self, from: Data(contentsOf: url)))
    }
}
